#!/usr/bin/env python3
"""Build TASKS.md as a generated index of per-task files under tasks/ (pilot, schema 2).

Each task lives in tasks/<ID>.md with the task contract as `- Field: value` lines
under a `# <ID> — <title>` heading, plus `#### Next action`. `- Kind: known-issue`
files under `## Known issues`. The Overdue section depends on today's date, so
rebuild at boot; `--check` then fails only when a task file changed unbuilt. The root TASKS.md is
regenerated from those files and is never edited by hand: one line per task,
sorted overdue first, then by due date. The contract checks the validator makes on
TASKS.md entries (fields, vocabulary, packet exists) are made here on tasks/*.md.

    build_task_index.py --root .           # rewrite TASKS.md
    build_task_index.py --root . --check   # exit 1 if TASKS.md is stale or a task file is malformed
"""

from __future__ import annotations

import argparse
import datetime as dt
import re
import sys
from pathlib import Path

REQUIRED = ("Status", "Priority", "Owner", "Area", "Due", "Depends-on", "Approval", "Approval-packet", "Evidence")
OPEN_SECTIONS = (("Active", ("proposed", "ready", "in-progress", "blocked", "review")), ("Waiting", ("waiting",)))
CLOSED = ("completed", "cancelled", "archived")
NEXT_MAX = 110
HEADER = "# Tasks — generated index\n\nGenerated by `build_task_index.py` from `tasks/*.md`; do not edit. Open a task by its file; history is in its `- Log:`.\n"


def field(text: str, name: str) -> str:
    m = re.search(rf"(?m)^- {re.escape(name)}:\s*(.*)$", text)
    return m.group(1).strip() if m else ""


def next_action(text: str) -> str:
    m = re.search(r"(?ms)^#### Next action[^\n]*\n+(.*?)(?=^#{1,4} |\Z)", text)
    if not m:
        return ""
    para = " ".join(m.group(1).strip().split("\n\n")[0].split()).removeprefix("- ")
    return para if len(para) <= NEXT_MAX else para[: NEXT_MAX - 1].rstrip() + "…"


def load(root: Path, errors: list[str]) -> list[dict]:
    tasks, seen = [], set()
    for path in sorted((root / "tasks").glob("*.md")):
        text = path.read_text(encoding="utf-8")
        head = re.match(r"# (\S+) — (.+)", text)
        if not head:
            errors.append(f"{path.name}: first line must be '# <ID> — <title>'")
            continue
        tid, title = head.group(1), head.group(2).strip()
        if path.stem != tid:
            errors.append(f"{path.name}: file name does not match ID {tid}")
        if tid in seen:
            errors.append(f"{tid}: duplicate ID")
        seen.add(tid)
        t = {"id": tid, "title": title, "path": f"tasks/{path.name}", "next": next_action(text)}
        for name in REQUIRED + ("Log", "Kind", "Facts"):
            t[name] = field(text, name)
        for name in REQUIRED:
            if not t[name]:
                errors.append(f"{tid}: missing '- {name}:' line")
        due = t["Due"].split()[0] if t["Due"] else ""
        if due and due != "none" and not re.fullmatch(r"\d{4}-\d{2}-\d{2}", due):
            errors.append(f"{tid}: Due must be YYYY-MM-DD or none (got {t['Due']})")
        t["due"] = None if due in ("", "none") else due
        for named in re.findall(r"approvals/[A-Za-z0-9._-]+\.md", t["Approval-packet"]):
            if not (root / named).is_file():
                errors.append(f"{tid}: approval packet not found: {named}")
        for linked in re.findall(r"(?:facts|artifacts)/[A-Za-z0-9._/-]+\.md", t["Facts"] + " " + t["Log"]):
            if not (root / linked).is_file():
                errors.append(f"{tid}: linked file not found: {linked}")
        t["status"] = (re.match(r"[a-z-]+", t["Status"]) or [""])[0]
        if t["status"] not in CLOSED and not t["next"]:
            errors.append(f"{tid}: open task has no '#### Next action' paragraph")
        tasks.append(t)
    ids = {t["id"] for t in tasks}
    archived = " ".join(p.read_text(encoding="utf-8") for p in root.glob("archive/tasks-*.md"))
    for t in tasks:
        for dep in re.findall(r"[A-Z]+-\d{4}", t["Depends-on"]):
            if dep not in ids and f"### {dep} " not in archived:
                errors.append(f"{t['id']}: depends on unknown {dep}")
    return tasks


def line(t: dict, today: str) -> str:
    over = " OVERDUE" if t["due"] and t["due"] < today and t["status"] not in CLOSED else ""
    due = f" · due {t['due']}{over}" if t["due"] else ""
    ids = re.findall(r"[A-Z]+-\d{4}", t["Depends-on"])
    deps = f" · after {', '.join(ids)}" if ids else ""
    nxt = t["next"] if len(t["next"]) <= NEXT_MAX else t["next"][: NEXT_MAX - 1].rstrip() + "…"
    return f"- [{t['id']}]({t['path']}) {t['status']} · {t['Area']}{due}{deps} — {t['title']}. Next: {nxt}\n"


def render(tasks: list[dict], today: str) -> str:
    def key(t: dict) -> tuple:
        return (not (t["due"] and t["due"] < today), t["due"] is None, t["due"] or "", t["Area"], t["id"])

    out = [HEADER]
    for name, statuses in OPEN_SECTIONS:
        body = "".join(line(t, today) for t in sorted(tasks, key=key) if t["status"] in statuses and t["Kind"] != "known-issue")
        out.append(f"## {name}\n\n" + (body or "None.\n"))
    known = [t for t in sorted(tasks, key=key) if t["Kind"] == "known-issue" and t["status"] not in CLOSED]
    out.append("## Known issues\n\n" + ("".join(line(t, today) for t in known) or "None.\n"))
    done = [t for t in tasks if t["status"] in CLOSED]
    out.append("## Completed\n\n" + "".join(f"- [{t['id']}]({t['path']}) {t['title']}\n" for t in done)
               + "\nOlder: `archive/tasks-YYYY-MM.md`.\n")
    return "\n".join(x.rstrip("\n") + "\n" for x in out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", required=True)
    ap.add_argument("--check", action="store_true", help="fail if TASKS.md differs from a fresh build")
    ap.add_argument("--today", default=dt.date.today().isoformat(), help=argparse.SUPPRESS)
    args = ap.parse_args()
    root = Path(args.root)
    errors: list[str] = []
    if not (root / "tasks").is_dir():
        print("ERROR: no tasks/ directory", file=sys.stderr)
        return 1
    tasks = load(root, errors)
    text = render(tasks, args.today)
    for e in errors:
        print(f"ERROR: {e}", file=sys.stderr)
    target = root / "TASKS.md"
    if args.check:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current != text:
            print("ERROR: TASKS.md is stale; run build_task_index.py --root .", file=sys.stderr)
            return 1
        return 1 if errors else 0
    if errors:
        return 1
    target.write_text(text, encoding="utf-8")
    print(f"wrote TASKS.md: {len(tasks)} tasks, {len(text.encode())} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
